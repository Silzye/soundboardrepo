/* =========================================================================
   Diagnostics (Settings > System > Copy diagnostics)
   Plain-text facts that make a bug report actionable. Nothing secret goes
   in: no cookies, and the home folder path is masked.
   ========================================================================= */
ipcMain.handle("get-diagnostics", async () => {
  const os = require("os");
  const home = os.homedir();
  const mask = (text) => String(text ?? "").split(home).join("~");
  const maskDeep = (v) => {
    if (typeof v === "string") return mask(v);
    if (Array.isArray(v)) return v.map(maskDeep);
    if (v && typeof v === "object") return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, maskDeep(x)]));
    return v;
  };
  let rvc = null;
  try { rvc = await getRvcBackendStatus(); } catch (e) { rvc = { error: e?.message || String(e) }; }
  let ytdlp = false;
  try { ytdlp = ytdlpIsUsable(); } catch {}
  let settings = {};
  try { settings = readSettingsFile(); } catch {}
  return {
    app: { version: app.getVersion(), packaged: app.isPackaged },
    versions: { node: process.versions.node },
    system: {
      platform: process.platform,
      arch: process.arch,
      osRelease: os.release(),
      totalMemoryGB: Math.round((os.totalmem() / 1024 ** 3) * 10) / 10,
    },
    library: { soundCount: readSoundsFile().length },
    ytdlpReady: ytdlp,
    rvc: maskDeep(rvc),
    settings: maskDeep(settings),
    logFile: mask(logFilePath),
    recentLog: logBuffer.slice(-60).map(mask),
  };
});


