/* =========================================================================
   Text-to-Speech — Flowery TTS (https://flowery.pw), a free public TTS
   API. Voices list is cached in memory for the session (850+ voices,
   no need to refetch every time the TTS page opens). Generated audio is
   cached to disk by a hash of its exact parameters, so re-generating the
   same line/voice/settings is instant on repeat.
   ========================================================================= */
const FLOWERY_API_BASE = "https://api.flowery.pw/v1";
const FLOWERY_UA = {
  "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36",
  "Accept": "application/json, */*",
  "Referer": "https://flowery.pw/",
  "Origin": "https://flowery.pw",
};
let cachedTtsVoices = null;

async function fetchFloweryVoices(base) {
  const res = await fetch(`${base}/tts/voices`, { headers: FLOWERY_UA, signal: AbortSignal.timeout(20000) });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
  const data = await res.json();
  const rawVoices = Array.isArray(data) ? data
    : Array.isArray(data?.voices) ? data.voices
    : Array.isArray(data?.data) ? data.data
    : null;
  if (!rawVoices) throw new Error("Unexpected response shape: " + JSON.stringify(data).slice(0, 300));
  return rawVoices;
}

ipcMain.handle("tts-list-voices", async () => {
  if (cachedTtsVoices) return { success: true, voices: cachedTtsVoices, cached: true };
  let rawVoices;
  let lastErr;
  for (const base of [FLOWERY_API_BASE, "https://api.flowery.pw"]) {
    try {
      rawVoices = await fetchFloweryVoices(base);
      break;
    } catch (e) {
      lastErr = e;
    }
  }
  if (!rawVoices) {
    return { success: false, error: lastErr?.message || "Couldn't reach Flowery TTS" };
  }
  cachedTtsVoices = rawVoices
    .map((v) => ({
      id: v.name || v.id || v.voice,
      name: v.name || v.id || v.voice,
      gender: v.gender || "",
      language: v.language?.name || v.language?.code || v.language || "",
    }))
    .filter((v) => v.id)
    .sort((a, b) => a.name.localeCompare(b.name));
  return { success: true, voices: cachedTtsVoices };
});

ipcMain.handle("tts-generate", async (_, { text, voice, translate, speed }) => {
  try {
    if (!text || !text.trim()) return { success: false, error: "No text provided" };
    if (!voice) return { success: false, error: "No voice selected" };

    const clampedSpeed = Math.min(2, Math.max(0.5, Number(speed) || 1));
    const params = new URLSearchParams({
      text: text.slice(0, 2000),
      voice,
      translate: translate ? "true" : "false",
      audio_format: "mp3",
      speed: clampedSpeed.toFixed(1),
    });

    const cacheKey = crypto.createHash("sha1").update(params.toString()).digest("hex");
    const outputPath = path.join(ttsGeneratedDir, `${cacheKey}.mp3`);
    try {
      if (fs.statSync(outputPath).size > 0) return { success: true, filePath: outputPath, cached: true };
    } catch {}

    // Try each API base in turn — a network error on the first one (not just
    // a bad status) should fall through to the second instead of failing.
    let res = null, failedRes = null, lastErr = null;
    for (const base of [FLOWERY_API_BASE, "https://api.flowery.pw"]) {
      try {
        const r = await fetch(`${base}/tts?${params.toString()}`, { headers: FLOWERY_UA, signal: AbortSignal.timeout(45000) });
        if (r.ok) { res = r; break; }
        failedRes = r;
      } catch (e) {
        lastErr = e;
      }
    }
    if (!res) {
      if (failedRes) {
        const detail = await failedRes.text().catch(() => "");
        throw new Error(`Flowery API returned ${failedRes.status}${detail ? `: ${detail.slice(0, 200)}` : ""}`);
      }
      throw new Error(lastErr?.name === "TimeoutError" ? "Flowery TTS timed out" : (lastErr?.message || "Couldn't reach Flowery TTS"));
    }
    const contentType = res.headers.get("content-type") || "";
    const buffer = Buffer.from(await res.arrayBuffer());
    if (!buffer.length || /json|html|text\//i.test(contentType)) {
      throw new Error("Flowery returned an error instead of audio" + (buffer.length ? `: ${buffer.toString("utf8", 0, 200)}` : ""));
    }
    // Write to a temp name first so a half-written file is never served from cache.
    const tmpOut = outputPath + ".tmp";
    fs.writeFileSync(tmpOut, buffer);
    fs.renameSync(tmpOut, outputPath);
    return { success: true, filePath: outputPath };
  } catch (e) {
    return { success: false, error: e?.message || "TTS generation failed" };
  }
});

