// Chromium's decoder can't read every format the file picker accepts (WMA,
// AIFF, ...). The renderer calls this when decodeAudioData fails; ffmpeg
// converts the file to WAV once and the result is cached by path+size+mtime.
const transcodeCacheDir = path.join(userDataPath, "transcoded");
try { fs.mkdirSync(transcodeCacheDir, { recursive: true }); } catch {}

const transcodeInFlight = new Map();
ipcMain.handle("transcode-to-wav", (_, filePath) => {
  // Several cards asking for the same file at once share a single ffmpeg run.
  const key = typeof filePath === "string" ? filePath : null;
  if (key && transcodeInFlight.has(key)) return transcodeInFlight.get(key);
  const job = transcodeToWav(filePath);
  if (key) {
    transcodeInFlight.set(key, job);
    job.finally(() => transcodeInFlight.delete(key)).catch(() => {});
  }
  return job;
});

async function transcodeToWav(filePath) {
  let tmpPath = null;
  try {
    if (typeof filePath !== "string" || !fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) {
      return { success: false, error: "File not found" };
    }
    const st = fs.statSync(filePath);
    const key = crypto.createHash("sha1").update(`${filePath}|${st.size}|${st.mtimeMs}`).digest("hex");
    const outPath = path.join(transcodeCacheDir, key + ".wav");
    if (fs.existsSync(outPath) && fs.statSync(outPath).size > 44) return { success: true, outputPath: outPath };
    tmpPath = outPath + ".part";
    await new Promise((resolve, reject) => {
      ffmpeg(filePath).format("wav").audioCodec("pcm_s16le")
        .on("error", reject).on("end", resolve).save(tmpPath);
    });
    fs.renameSync(tmpPath, outPath);
    return { success: true, outputPath: outPath };
  } catch (e) {
    if (tmpPath) { try { fs.unlinkSync(tmpPath); } catch {} }
    return { success: false, error: e?.message || "Transcode failed" };
  }
}


