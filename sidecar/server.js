function extractZipWindows(zipPath, destDir) {
  return new Promise((resolve, reject) => {
    // Single-quoted PowerShell strings don't expand "$" and only need "'"
    // doubled — a profile folder like C:\Users\O'Brien or one containing "$"
    // broke the old double-quoted version.
    const q = (p) => `'${String(p).replace(/'/g, "''")}'`;
    const psCmd = `Expand-Archive -LiteralPath ${q(zipPath)} -DestinationPath ${q(destDir)} -Force`;
    const proc = spawn("powershell", ["-NoProfile", "-Command", psCmd], { windowsHide: true });
    let stderr = "";
    proc.stderr.on("data", (d) => { stderr += d.toString(); });
    proc.on("error", reject);
    proc.on("close", (code) => (code === 0 ? resolve() : reject(new Error(stderr.trim() || "Extraction failed"))));
  });
}

// Downloads to "<dest>.part" and only renames onto the real path once the
// whole file arrived — so an interrupted download can never leave a
// truncated file behind that later gets mistaken for a finished one.
// opts.onProgress(received, total) reports progress; opts.session.abort is set
// so a cancel button can stop the request mid-download.
function downloadFile(url, destPath, redirectsLeft = 5, opts = {}) {
  return new Promise((resolve, reject) => {
    const partPath = destPath + ".part";
    const req = https.get(url, { headers: { "User-Agent": "soundboard-app" } }, (res) => {
      if ([301, 302, 303, 307, 308].includes(res.statusCode) && res.headers.location) {
        res.resume();
        if (redirectsLeft <= 0) { reject(new Error("Too many redirects")); return; }
        let next;
        try { next = new URL(res.headers.location, url).toString(); }
        catch { reject(new Error("Invalid redirect from server")); return; }
        downloadFile(next, destPath, redirectsLeft - 1, opts).then(resolve, reject);
        return;
      }
      if (res.statusCode !== 200) {
        res.resume();
        reject(new Error(`Download failed with status ${res.statusCode}`));
        return;
      }
      const fileStream = fs.createWriteStream(partPath);
      let settled = false;
      const fail = (err) => {
        if (settled) return;
        settled = true;
        fileStream.destroy();
        try { fs.unlinkSync(partPath); } catch {}
        reject(err);
      };
      res.on("error", fail);
      res.on("close", () => { if (!res.complete) fail(new Error("Download was interrupted")); });
      fileStream.on("error", fail);
      fileStream.on("finish", () => {
        fileStream.close((closeErr) => {
          if (settled) return;
          if (closeErr) { fail(closeErr); return; }
          if (!res.complete) { fail(new Error("Download was interrupted")); return; }
          try { fs.renameSync(partPath, destPath); }
          catch (e) { fail(e); return; }
          settled = true;
          resolve();
        });
      });
      if (opts.onProgress) {
        const total = Number(res.headers["content-length"]) || 0;
        let received = 0;
        res.on("data", (chunk) => { received += chunk.length; opts.onProgress(received, total); });
      }
      res.pipe(fileStream);
    });
    if (opts.session) opts.session.abort = () => req.destroy(new Error("Download cancelled"));
    req.on("error", reject);
    req.setTimeout(30000, () => req.destroy(new Error("Download timed out")));
  });
}

const YTDLP_MIN_BYTES = 1024 * 1024; // the real binary is tens of MB; anything tiny is a broken download
const YTDLP_STALE_MS = 7 * 24 * 60 * 60 * 1000;
let ytdlpEnsurePromise = null;
let ytdlpUpdateChecked = false;

function ytdlpIsUsable() {
  try { return fs.statSync(ytdlpPath).size >= YTDLP_MIN_BYTES; } catch { return false; }
}

// yt-dlp breaks whenever YouTube changes something and is fixed by a new
// release — so a copy downloaded once and never refreshed slowly rots.
// Best-effort self-update (once per launch, only if the binary is a week old).
function updateYtDlp(exePath) {
  return new Promise((resolve) => {
    let proc;
    try { proc = spawn(exePath, ["-U"], { windowsHide: true }); } catch { resolve(); return; }
    const timer = setTimeout(() => { try { proc.kill(); } catch {} resolve(); }, 45000);
    proc.on("error", () => { clearTimeout(timer); resolve(); });
    proc.on("close", () => { clearTimeout(timer); resolve(); });
  });
}

async function ensureYtDlp() {
  if (!ytdlpEnsurePromise) {
    ytdlpEnsurePromise = (async () => {
      if (!ytdlpIsUsable()) {
        try { fs.unlinkSync(ytdlpPath); } catch {}
        fs.mkdirSync(ytdlpDir, { recursive: true });
        console.log("[YT] Downloading yt-dlp (one-time setup)...");
        await downloadFile(ytdlpReleaseUrl(), ytdlpPath);
        if (process.platform !== "win32") fs.chmodSync(ytdlpPath, 0o755);
        ytdlpUpdateChecked = true;
      } else if (!ytdlpUpdateChecked) {
        ytdlpUpdateChecked = true;
        try {
          if (Date.now() - fs.statSync(ytdlpPath).mtimeMs > YTDLP_STALE_MS) await updateYtDlp(ytdlpPath);
        } catch {}
      }
      return ytdlpPath;
    })().finally(() => { ytdlpEnsurePromise = null; });
  }
  return ytdlpEnsurePromise;
}

function runYtDlpJson(exePath, url) {
  return new Promise((resolve, reject) => {
    const proc = spawn(exePath, ["--dump-json", "--no-warnings", "--no-playlist", ...ytCookieArgs(), url], { windowsHide: true });
    let stdout = "", stderr = "";
    proc.stdout.on("data", (d) => { stdout += d.toString(); });
    proc.stderr.on("data", (d) => { stderr += d.toString(); });
    const timer = setTimeout(() => { proc.kill(); reject(new Error("Timed out fetching video info")); }, 30000);
    proc.on("error", (e) => { clearTimeout(timer); reject(e); });
    proc.on("close", (code) => {
      clearTimeout(timer);
      if (code !== 0) { reject(new Error(stderr.trim() || `yt-dlp exited with code ${code}`)); return; }
      try { resolve(JSON.parse(stdout)); } catch { reject(new Error("Couldn't parse video info")); }
    });
  });
}

function runYtDlpDownload(exePath, url, outputTemplate) {
  return new Promise((resolve, reject) => {
    const proc = spawn(exePath, ["-f", "bestaudio/best", "--no-playlist", "--no-progress", "--no-warnings", ...ytCookieArgs(), "-o", outputTemplate, url], { windowsHide: true });
    let stderr = "";
    // Nothing reads stdout, and an unread pipe fills up (about 64 KB) and
    // freezes the child, so drain it.
    proc.stdout.resume();
    proc.stderr.on("data", (d) => { stderr = (stderr + d.toString()).slice(-4000); });
    const timer = setTimeout(() => { proc.kill(); reject(new Error("Download timed out")); }, 180000);
    proc.on("error", (e) => { clearTimeout(timer); reject(e); });
    proc.on("close", (code) => {
      clearTimeout(timer);
      if (code !== 0) { reject(new Error(stderr.trim() || `yt-dlp exited with code ${code}`)); return; }
      resolve();
    });
  });
}

