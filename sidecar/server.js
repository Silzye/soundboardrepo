// yt-dlp leaves "<name>.part" / ".ytdl" files behind when a download fails;
// remove everything it wrote under this import's temp prefix.
function removeTempFiles(dir, prefix) {
  if (!prefix) return;
  try {
    for (const f of fs.readdirSync(dir)) {
      if (f.startsWith(prefix)) { try { fs.unlinkSync(path.join(dir, f)); } catch {} }
    }
  } catch {}
}

ipcMain.handle("youtube-import", async (_, payload) => {
  const { url, name, start, end, autoTrim } = payload || {};
  let tempAudioPath = null;
  let tempPrefix = null;
  let outPath = null;
  try {
    if (!url || !YOUTUBE_URL_RE.test(url)) {
      return { success: false, error: "That doesn't look like a valid YouTube URL" };
    }

    const startSec = parseTimeToSeconds(start);
    const endSec = parseTimeToSeconds(end);
    if (start && startSec == null) return { success: false, error: "Start time should look like mm:ss" };
    if (end && endSec == null) return { success: false, error: "End time should look like mm:ss" };
    if (startSec != null && endSec != null && endSec <= startSec) {
      return { success: false, error: "End time must be after start time" };
    }

    const exePath = await ensureYtDlp();
    const id = "yt_" + Date.now() + "_" + Math.random().toString(36).slice(2, 7);
    outPath = path.join(importedSoundsDir, id + ".mp3");
    const tempBase = path.join(importedSoundsDir, `${id}_src`);
    tempPrefix = `${id}_src.`;

    await runYtDlpDownload(exePath, url, `${tempBase}.%(ext)s`);

    const producedFile = fs.readdirSync(importedSoundsDir).find((f) => f.startsWith(`${id}_src.`) && !/\.(part|ytdl)$/.test(f));
    if (!producedFile) throw new Error("Download finished but no audio file was produced");
    tempAudioPath = path.join(importedSoundsDir, producedFile);

    await new Promise((resolve, reject) => {
      let command = ffmpeg(tempAudioPath).audioBitrate(128).format("mp3");

      if (startSec != null && startSec > 0) command = command.setStartTime(startSec);
      if (endSec != null) {
        const clipDuration = startSec != null ? endSec - startSec : endSec;
        command = command.setDuration(Math.max(0.1, clipDuration));
      }

      // Auto-trim: strip near-silence from the head and tail so grabbed
      // clips don't carry a chunk of dead air before/after the punchline.
      // (The reverse/re-reverse pair trims the tail using the same filter
      // that natively only trims the head.)
      if (autoTrim) {
        command = command.audioFilters([
          "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.15:detection=peak",
          "areverse",
          "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.15:detection=peak",
          "areverse",
        ]);
      }

      command.on("error", reject).on("end", resolve).save(outPath);
    });

    return { success: true, filePath: outPath, name: (name || "Imported clip").trim() };
  } catch (e) {
    console.error("youtube-import failed:", e);
    if (outPath) { try { fs.unlinkSync(outPath); } catch {} }
    return { success: false, error: e?.message || "Import failed for an unknown reason" };
  } finally {
    if (tempAudioPath) { try { fs.unlinkSync(tempAudioPath); } catch {} }
    removeTempFiles(importedSoundsDir, tempPrefix);
  }
});


/* =========================================================================
   Music Converter (sidebar) — full-song RVC conversion with vocal
   separation baked in by default, from a local file or a YouTube URL.
   Reuses the exact same yt-dlp download and RVC conversion pipeline as
   the sound library / AI Voices tab (youtube-import, convert-rvc-file).
   ========================================================================= */
ipcMain.handle("music-import-youtube", async (_, payload) => {
  const { url, name } = payload || {};
  let tempAudioPath = null;
  let tempPrefix = null;
  let outPath = null;
  try {
    if (!url || !YOUTUBE_URL_RE.test(url)) {
      return { success: false, error: "That doesn't look like a valid YouTube URL" };
    }
    const exePath = await ensureYtDlp();
    const id = "music_" + Date.now() + "_" + Math.random().toString(36).slice(2, 7);
    outPath = path.join(importedSoundsDir, id + ".mp3");
    const tempBase = path.join(importedSoundsDir, `${id}_src`);
    tempPrefix = `${id}_src.`;
    await runYtDlpDownload(exePath, url, `${tempBase}.%(ext)s`);
    const producedFile = fs.readdirSync(importedSoundsDir).find((f) => f.startsWith(`${id}_src.`) && !/\.(part|ytdl)$/.test(f));
    if (!producedFile) throw new Error("Download finished but no audio file was produced");
    tempAudioPath = path.join(importedSoundsDir, producedFile);
    await new Promise((resolve, reject) => {
      ffmpeg(tempAudioPath).audioBitrate(192).format("mp3").on("error", reject).on("end", resolve).save(outPath);
    });
    return { success: true, filePath: outPath, name: (name || "Imported song").trim() };
  } catch (e) {
    console.error("music-import-youtube failed:", e);
    if (outPath) { try { fs.unlinkSync(outPath); } catch {} }
    return { success: false, error: e?.message || "Import failed for an unknown reason" };
  } finally {
    if (tempAudioPath) { try { fs.unlinkSync(tempAudioPath); } catch {} }
    removeTempFiles(importedSoundsDir, tempPrefix);
  }
});

/* =========================================================================
   Live Voice Changer (sidebar) — keeps a warm rvc-python API server
   process running (`python -m rvc_python api -mp <model> -p <port>`) so
   the model loads ONCE, then short mic chunks recorded in the renderer
   are POSTed to its /convert endpoint and the converted audio is sent
   back. This is chunk-based, not sample-level streaming — expect roughly
   1-3 seconds of latency per chunk (hardware-dependent), not instant
   like a dedicated real-time voice-changer app.
   ========================================================================= */
let liveVoiceProcess = null;
let liveVoicePort = null;

function stopLiveVoiceProcess() {
  if (liveVoiceProcess) {
    killProcessTree(liveVoiceProcess);
    liveVoiceProcess = null;
  }
  liveVoicePort = null;
}

// Asks the OS for an unused port, so a leftover server from a previous run
// (or anything else on a fixed port) can't be mistaken for the new one.
function getFreePort() {
  return new Promise((resolve, reject) => {
    const srv = net.createServer();
    srv.unref();
    srv.on("error", reject);
    srv.listen(0, "127.0.0.1", () => {
      const { port } = srv.address();
      srv.close(() => resolve(port));
    });
  });
}

async function waitForLiveVoiceServer(port, proc, timeoutMs = 90000) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    if (proc.exitCode !== null || proc.signalCode) {
      throw new Error("The RVC API server exited before it was ready — check the log for errors");
    }
    try {
      const res = await fetch(`http://127.0.0.1:${port}/models`, { signal: AbortSignal.timeout(3000) });
      if (res.ok) return true;
    } catch {}
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error("RVC API server didn't come up in time — check the log for errors");
}

ipcMain.handle("live-voice-start", async (_, { voiceId, pitch }) => {
  try {
    stopLiveVoiceProcess();

    if (!isSafeName(voiceId)) return { success: false, error: "Invalid voice" };
    const modelPath = path.join(rvcVoicesDir, voiceId + ".pth");
    const indexPath = path.join(rvcVoicesDir, voiceId + ".index");
    if (!fs.existsSync(modelPath)) return { success: false, error: "Voice model file not found" };

    const { command: python } = await resolveRvcPython();
    const port = await getFreePort();
    const device = await resolveRvcDevice(python);
    let command = `${python} -m rvc_python api -mp "${modelPath}" -p ${port} -l`;
    if (device) command += ` -de ${device}`;
    if (fs.existsSync(indexPath)) command += ` -ip "${indexPath}"`;
    if (pitch) command += ` -pi ${-Math.round(pitch)}`; // same negation convention as runRvcConversion

    console.log(`[LiveVoice] Starting: ${command}`);
    const proc = spawnShell(command);
    liveVoiceProcess = proc;
    liveVoicePort = port;

    proc.stdout.on("data", (d) => sendToRenderer("rvc-conversion-log", d.toString()));
    proc.stderr.on("data", (d) => sendToRenderer("rvc-conversion-log", d.toString()));
    proc.on("error", (e) => console.error("[LiveVoice] process error:", e));
    // Only clear the shared state if this is still the current process — an
    // older process exiting late must not wipe out a newer one's entry.
    proc.on("exit", () => {
      if (liveVoiceProcess === proc) { liveVoiceProcess = null; liveVoicePort = null; }
    });

    await waitForLiveVoiceServer(port, proc);
    return { success: true, port };
  } catch (e) {
    stopLiveVoiceProcess();
    return { success: false, error: e?.message || "Couldn't start the live voice server" };
  }
});

ipcMain.handle("live-voice-stop", () => {
  stopLiveVoiceProcess();
  return { success: true };
});

// audioBase64 is one chunk of mic audio. The renderer now sends it as a
// ready-made 16-bit mono WAV (format: "wav"), which goes straight to the
// RVC server with no temp files and no ffmpeg process. The old webm/opus
// path is kept as a fallback for any caller that still sends it.
ipcMain.handle("live-voice-convert-chunk", async (_, { audioBase64, format }) => {
  if (!liveVoicePort) return { success: false, error: "Live voice server isn't running" };
  if (typeof audioBase64 !== "string" || !audioBase64) return { success: false, error: "No audio data" };
  let tmpIn = null;
  let tmpWav = null;
  try {
    let wavBase64;
    if (format === "wav") {
      wavBase64 = audioBase64;
    } else {
      const stamp = `${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;
      tmpIn = path.join(rvcConvertedDir, `live_in_${stamp}.webm`);
      tmpWav = path.join(rvcConvertedDir, `live_in_${stamp}.wav`);
      fs.writeFileSync(tmpIn, Buffer.from(audioBase64, "base64"));
      await new Promise((resolve, reject) => {
        ffmpeg(tmpIn).audioChannels(1).audioFrequency(44100).format("wav")
          .on("error", reject).on("end", resolve).save(tmpWav);
      });
      wavBase64 = fs.readFileSync(tmpWav).toString("base64");
    }

    const res = await fetch(`http://127.0.0.1:${liveVoicePort}/convert`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ audio_data: wavBase64 }),
      signal: AbortSignal.timeout(30000),
    });
    if (!res.ok) {
      const detail = await res.text().catch(() => "");
      throw new Error(`Convert failed: ${res.status}${detail ? ` ${detail.slice(0, 200)}` : ""}`);
    }
    const outBuffer = Buffer.from(await res.arrayBuffer());
    return { success: true, audioBase64: outBuffer.toString("base64") };
  } catch (e) {
    return { success: false, error: e?.message || "Chunk conversion failed" };
  } finally {
    if (tmpIn) { try { fs.unlinkSync(tmpIn); } catch {} }
    if (tmpWav) { try { fs.unlinkSync(tmpWav); } catch {} }
  }
});





