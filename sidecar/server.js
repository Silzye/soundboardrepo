/* -----------------------------------------------------------------------
   Child-process helpers. Commands built from the person's settings run
   through a shell, and killing only the shell leaves the real worker
   (python/demucs/rvc server) running as an orphan — so kill the whole tree.
   ----------------------------------------------------------------------- */
function spawnShell(command) {
  return spawn(command, { shell: true, windowsHide: true, detached: process.platform !== "win32" });
}

function killProcessTree(proc) {
  if (!proc || !proc.pid || proc.exitCode !== null) return;
  try {
    if (process.platform === "win32") {
      spawn("taskkill", ["/pid", String(proc.pid), "/T", "/F"], { windowsHide: true });
    } else {
      process.kill(-proc.pid, "SIGTERM");
    }
  } catch {
    try { proc.kill(); } catch {}
  }
}

