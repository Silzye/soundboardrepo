// Runs "<python> <args>" through a shell (the setting can be a quoted path or
// "py -3.10") and resolves with { ok, out } instead of throwing.
function execPython(python, args, timeout = 20000) {
  return new Promise((resolve) => {
    exec(`${python} ${args}`, { windowsHide: true, timeout }, (err, stdout, stderr) =>
      resolve({ ok: !err, out: `${stdout || ""}${stderr || ""}`.trim() })
    );
  });
}

async function getPythonInfo(python) {
  const r = await execPython(python, "--version");
  if (!r.ok) return { found: false };
  const m = r.out.match(/Python\s+(\d+)\.(\d+)/i);
  // Unrecognised output: don't block the person over a parsing quirk.
  if (!m) return { found: true, versionText: r.out, compatible: true };
  const major = Number(m[1]);
  const minor = Number(m[2]);
  return {
    found: true,
    versionText: `${major}.${minor}`,
    compatible: major === 3 && minor >= RVC_PYTHON_MIN_MINOR && minor <= RVC_PYTHON_MAX_MINOR,
  };
}

async function hasPipPackage(python, name) {
  return (await execPython(python, `-m pip show ${name}`)).ok;
}

// Commands worth trying when the configured Python doesn't work, best first.
function getPythonCandidates() {
  if (process.platform === "win32") {
    const list = [];
    if (fs.existsSync(embeddedPythonExe)) list.push(`"${embeddedPythonExe}"`);
    list.push("py -3.10", "py -3.9", "python", "python3");
    return list;
  }
  return ["python3.10", "python3.9", "python3", "python"];
}

// The Python command to actually use: the configured one if it's compatible,
// otherwise the first compatible Python found on the machine (so someone with
// 3.12 as default and 3.10 installed alongside needs no manual setup). Not
// written back to settings — the renderer holds its own copy of settings and
// would overwrite it — so this is re-resolved each time it's needed.
async function resolveRvcPython() {
  const configured = readSettingsFile().rvcPythonCommand || SETTINGS_DEFAULTS.rvcPythonCommand;
  const configuredInfo = await getPythonInfo(configured);
  if (configuredInfo.found && configuredInfo.compatible) {
    return { command: configured, info: configuredInfo, autoDetected: false };
  }
  for (const candidate of getPythonCandidates()) {
    if (candidate === configured) continue;
    const info = await getPythonInfo(candidate);
    if (info.found && info.compatible) return { command: candidate, info, autoDetected: true };
  }
  return { command: configured, info: configuredInfo, autoDetected: false };
}

/* ---- Running long commands with progress ---- */

// Turns a line of pip output into a short "what's happening" label.
function pipLineToLabel(line) {
  let m = line.match(/^Collecting\s+([^\s;=<>!~[]+)/);
  if (m) return `Resolving ${m[1]}`;
  m = line.match(/^Downloading\s+(\S+)/);
  if (m) return `Downloading ${m[1]}`;
  if (/^Installing collected packages/i.test(line)) return "Installing packages (this can take a few minutes)";
  return null;
}

// Runs a long command, streaming output through `log` and each complete line
// through `onLine`. Rejects with the tail of stderr so the person sees what
// pip actually complained about, or with a cancelled error if the session
// was cancelled while it ran.
function runStreaming(command, log, label, session, onLine) {
  return new Promise((resolve, reject) => {
    const proc = spawnShell(command);
    if (session) session.proc = proc;
    let stderrTail = "";
    let pending = "";
    const handle = (text) => {
      log(text);
      if (!onLine) return;
      pending += text;
      const lines = pending.split(/\r?\n/);
      pending = lines.pop();
      for (const l of lines) if (l.trim()) onLine(l.trim());
    };
    proc.stdout.on("data", (d) => handle(d.toString()));
    proc.stderr.on("data", (d) => {
      const text = d.toString();
      handle(text);
      stderrTail = (stderrTail + text).slice(-1000);
    });
    proc.on("error", reject);
    proc.on("close", (code) => {
      if (session?.proc === proc) session.proc = null;
      if (session?.cancelled) { reject(cancelledError()); return; }
      if (code === 0) { resolve(); return; }
      const detail = stderrTail.trim();
      reject(new Error(`${label} exited with code ${code}` + (detail ? `: ${detail}` : "")));
    });
  });
}

// "pip <args>" with the progress bar following pip's own output.
function runPip(python, args, session, step, totalSteps, baseLabel) {
  sendSetupProgress(step, totalSteps, baseLabel);
  return runStreaming(`${python} -m pip ${args}`, sendBackendLog, "pip install", session, (line) => {
    const detail = pipLineToLabel(line);
    if (detail) sendSetupProgress(step, totalSteps, `${baseLabel} — ${detail}`);
  });
}

function downloadWithProgress(url, destPath, session, step, totalSteps, label) {
  sendSetupProgress(step, totalSteps, label, 0);
  let lastSent = 0;
  return downloadFile(url, destPath, 5, {
    session,
    onProgress: (received, total) => {
      const now = Date.now();
      if (now - lastSent < 150 && received !== total) return; // don't flood IPC
      lastSent = now;
      const percent = total ? Math.round((received / total) * 100) : null;
      const detail = percent !== null ? `${percent}%` : `${(received / 1048576).toFixed(1)} MB`;
      sendSetupProgress(step, totalSteps, `${label} — ${detail}`, percent);
    },
  });
}

// The embeddable distro ships with site-packages disabled (a "._pth" file
// with "#import site" commented out) — pip needs it enabled. Safe to repeat.
function enableEmbeddedSitePackages() {
  const pthFile = fs.readdirSync(embeddedPythonDir).find((f) => f.endsWith("._pth"));
  if (!pthFile) return;
  const pthPath = path.join(embeddedPythonDir, pthFile);
  const content = fs.readFileSync(pthPath, "utf-8").replace(/^#\s*import site/m, "import site");
  fs.writeFileSync(pthPath, content);
}

