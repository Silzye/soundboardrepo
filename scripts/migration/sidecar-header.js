"use strict";

/*
 * Soundboard backend sidecar.
 *
 * Runs as a child process of the Tauri app and handles everything that needs
 * Python, yt-dlp, ffmpeg or the network. The logic below is the original
 * Electron main process, unchanged, with Electron's IPC replaced by a tiny
 * line-delimited JSON protocol over stdin/stdout:
 *
 *   Rust -> sidecar (stdin):   {"id":1,"channel":"check-rvc-backend","args":null}
 *   sidecar -> Rust (stdout):  {"id":1,"ok":true,"result":{...}}
 *                              {"id":1,"ok":false,"error":"message"}
 *                              {"event":"rvc-backend-log","payload":"..."}   (pushed to the UI)
 *
 * stdout is reserved for that protocol, so console.log goes to stderr.
 * Window controls, dialogs, hotkeys, the updater, and sounds/settings
 * persistence live in Rust (src-tauri/src).
 *
 * GENERATED by scripts/extract-sidecar.py from the original main.js.
 */
const util = require("util");

console.log = (...args) => { try { process.stderr.write(util.format(...args) + "\n"); } catch {} };
console.info = console.log;
process.stdout.on("error", () => {});

const app = {
  getVersion: () => process.env.SOUNDBOARD_APP_VERSION || "0.0.0",
  isPackaged: process.env.SOUNDBOARD_PACKAGED === "1",
};

const handlers = new Map();
const ipcMain = {
  handle: (channel, fn) => handlers.set(channel, fn),
  on: (channel, fn) => handlers.set(channel, fn),
};

function writeLine(obj) {
  try { process.stdout.write(JSON.stringify(obj) + "\n"); } catch {}
}

// Pushes an event to the UI (Rust re-emits it as a Tauri event).
function sendToRenderer(channel, payload) {
  writeLine({ event: channel, payload: payload === undefined ? null : payload });
}
